"""Run the offline probe against the five recorded validation scenes.

Each scene is one npz recording with a known ground-truth planar pose.  The
script extracts one representative body-frame sweep per scene, writes it as a
PCD, runs ``relocalizer_probe`` and compares the returned pose with the
reference.  It prints a markdown table and exits non-zero when a scene is not
confirmed or exceeds the tolerance.

Example:
    ros2 run relocalizer run_validation.py --recordings /data/body \
        --plan /maps/site.yaml --surface /maps/site.pcd --threads 8
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
from ament_index_python.packages import get_package_prefix

# scene name, frame index, reference (x, y, heading_deg).  The frame indices are
# the leading-quality frames picked while preparing the recordings.
SCENES = (
    ("x:0_y:0_yaw:0", 120, (0.0, 0.0, 0.0)),
    ("x:0_y:0_yaw:90", 30, (0.0, 0.0, 90.0)),
    ("x:0_y:0_yaw:180", 201, (0.0, 0.0, 180.0)),
    ("x:0_y:-2.0_yaw:90", 30, (0.0, -2.0, 90.0)),
    ("x:0.9_y:1.5_yaw:0", 85, (0.9, 1.5, 0.0)),
)

POSE_PATTERN = re.compile(
    r"pose: x=(?P<x>-?[\d.]+) y=(?P<y>-?[\d.]+) "
    r"heading=(?P<h>-?[\d.]+) confidence=(?P<c>-?[\d.]+)")
ERROR_PATTERN = re.compile(
    r"reference error: dx=(?P<dx>-?[\d.]+) dy=(?P<dy>-?[\d.]+) "
    r"distance=(?P<d>-?[\d.]+) heading=(?P<h>-?[\d.]+) deg")
SEARCH_PATTERN = re.compile(r"search: (?P<ms>[\d.]+) ms")


def frame_points(recording: Path, index: int) -> np.ndarray:
    data = np.load(recording)
    counts = data["counts"]
    if index < 0:
        index += len(counts)
    if index < 0 or index >= len(counts):
        raise IndexError(f"frame {index} is outside recording {recording} (0..{len(counts) - 1})")
    offsets = np.concatenate([[0], np.cumsum(counts)])
    return np.asarray(data["xyz"][offsets[index]:offsets[index + 1]], dtype=np.float32)


def write_pcd(path: Path, points: np.ndarray) -> None:
    points = points.reshape(-1, 3)
    header = (
        "# .PCD v0.7 - generated by run_validation.py\n"
        "VERSION 0.7\nFIELDS x y z\nSIZE 4 4 4\nTYPE F F F\nCOUNT 1 1 1\n"
        f"WIDTH {len(points)}\nHEIGHT 1\nVIEWPOINT 0 0 0 1 0 0 0\n"
        f"POINTS {len(points)}\nDATA binary\n"
    )
    with path.open("wb") as stream:
        stream.write(header.encode("ascii"))
        points.astype("<f4").tofile(stream)


def run_probe(probe: Path, plan: Path, surface: Path, sweep: Path, reference, threads: int):
    command = [
        str(probe), "--plan", str(plan), "--surface", str(surface), "--sweep", str(sweep),
        "--reference", ",".join(str(value) for value in reference),
        "--threads", str(threads),
    ]
    completed = subprocess.run(command, capture_output=True, text=True, check=False)
    output = completed.stdout + completed.stderr
    pose = POSE_PATTERN.search(output)
    error = ERROR_PATTERN.search(output)
    search = SEARCH_PATTERN.search(output)
    if completed.returncode not in (0, 2) or pose is None or error is None:
        raise RuntimeError(f"probe failed for {sweep.name}:\n{output}")
    return {
        "confirmed": "confirmed: yes" in output,
        "x": float(pose.group("x")),
        "y": float(pose.group("y")),
        "heading": float(pose.group("h")),
        "confidence": float(pose.group("c")),
        "distance": float(error.group("d")),
        "turn": float(error.group("h")),
        "search_ms": float(search.group("ms")) if search else float("nan"),
    }


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--recordings", type=Path, required=True, help="directory containing the five NPZ scenes")
    parser.add_argument(
        "--plan", type=Path, required=True, help="map descriptor YAML")
    parser.add_argument(
        "--surface", type=Path, required=True, help="3-D map PCD")
    parser.add_argument(
        "--probe", type=Path,
        help="probe executable (default: installed relocalizer_probe)")
    parser.add_argument(
        "--workdir", type=Path, default=Path.cwd() / ".validation")
    parser.add_argument("--threads", type=int, default=8)
    parser.add_argument("--distance-tolerance", type=float, default=0.5)
    parser.add_argument("--heading-tolerance", type=float, default=5.0)
    args = parser.parse_args(argv)

    if args.probe is None:
        args.probe = Path(get_package_prefix("relocalizer")) / "lib/relocalizer/relocalizer_probe"
    args.probe = args.probe.resolve()
    inputs = [args.probe, args.plan, args.surface]
    inputs.extend(args.recordings / f"{name}.npz" for name, _, _ in SCENES)
    missing = [str(path) for path in inputs if not path.is_file()]
    if missing:
        parser.error("missing input files:\n" + "\n".join(missing))

    args.workdir.mkdir(parents=True, exist_ok=True)
    rows = []
    failures = 0
    for name, frame, reference in SCENES:
        recording = args.recordings / f"{name}.npz"
        sweep = args.workdir / f"{name.replace(':', '_')}_{frame}.pcd"
        write_pcd(sweep, frame_points(recording, frame))
        result = run_probe(
            args.probe, args.plan, args.surface, sweep, reference, args.threads)
        ok = (result["confirmed"] and result["distance"] <= args.distance_tolerance
              and abs(result["turn"]) <= args.heading_tolerance)
        failures += 0 if ok else 1
        rows.append((name, reference, result, ok))

    print("\n| scene | reference x,y,heading | estimate x,y,heading | error m | error deg "
          "| confidence | search ms | confirmed |")
    print("|---|---|---|---|---|---|---|---|")
    for name, reference, result, ok in rows:
        print(
            f"| `{name}` | {reference[0]:.2f}, {reference[1]:.2f}, {reference[2]:.0f} "
            f"| {result['x']:.3f}, {result['y']:.3f}, {result['heading']:.2f} "
            f"| {result['distance']:.3f} | {result['turn']:.2f} "
            f"| {result['confidence']:.3f} | {result['search_ms']:.0f} "
            f"| {'yes' if result['confirmed'] else 'no'} |")
    print(f"\n{len(SCENES) - failures}/{len(SCENES)} scenes within tolerance.")
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
