"""Extract one body-frame sweep from a recorded npz file and write it as a PCD.

The npz recordings used for validation store concatenated frames:
    stamps:  (N,)        timestamps
    counts:  (N,)        number of points in each frame
    xyz:     (M, 3)      concatenated float32 points
    reference: (3,)      x, y, heading_degrees of the recording beginning

Usage:
    python3 extract_sweep.py SCENE.npz FRAME_INDEX OUTPUT.pcd [--frame FILTERED]
"""

import argparse
import struct
import sys

import numpy as np


def load_frame(path, index):
    data = np.load(path)
    counts = data["counts"]
    if index < 0:
        index += len(counts)
    if index < 0 or index >= len(counts):
        raise IndexError(f"frame {index} is outside 0..{len(counts) - 1}")
    offsets = np.concatenate([[0], np.cumsum(counts)])
    return data["xyz"][offsets[index]:offsets[index + 1]]


def write_pcd(path, points):
    points = np.asarray(points, dtype=np.float32).reshape(-1, 3)
    header = (
        "# .PCD v0.7 - generated by relocalizer/scripts/extract_sweep.py\n"
        "VERSION 0.7\n"
        "FIELDS x y z\n"
        "SIZE 4 4 4\n"
        "TYPE F F F\n"
        "COUNT 1 1 1\n"
        f"WIDTH {points.shape[0]}\n"
        "HEIGHT 1\n"
        "VIEWPOINT 0 0 0 1 0 0 0\n"
        f"POINTS {points.shape[0]}\n"
        "DATA binary\n"
    )
    with open(path, "wb") as stream:
        stream.write(header.encode("ascii"))
        stream.write(struct.pack(f"<{points.size}f", *points.reshape(-1)))


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recording", help="npz file with stamps/counts/xyz")
    parser.add_argument("frame", type=int, help="frame index (negative is from the end)")
    parser.add_argument("output", help="destination PCD path")
    args = parser.parse_args(argv)

    points = load_frame(args.recording, args.frame)
    write_pcd(args.output, points)
    print(f"{args.output}: {points.shape[0]} points")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
